const {setup, assert, numeric} = require('./helpers.cjs');
const Engine = require('../src/engine.js');
const channel = {id:'google',model:'cpc',weight:1,cpc:2,ctr:5,clickToResult:10,resultToSale:20};
const result = Engine.calculate({months:1,monthlyBudget:1000,averageOrder:100,marginPct:50,uncertainty:20,channels:[channel]});
const base = result.scenarios.base;
assert.equal(base.total.budget,1000);
assert.equal(base.total.clicks,500);
assert.equal(base.total.impressions,10000);
assert.equal(base.total.results,50);
assert.equal(base.total.sales,10);
assert.equal(base.total.revenue,1000);
assert.ok(result.scenarios.optimistic.total.sales>base.total.sales);
assert.ok(result.scenarios.conservative.total.sales<base.total.sales);
const cpm = Engine.calculate({months:1,monthlyBudget:1000,averageOrder:100,channels:[{...channel,id:'meta',model:'cpm',cpm:10,ctr:1}]}).scenarios.base.total;
assert.equal(cpm.impressions,100000);
assert.equal(cpm.clicks,1000);
const t = setup();
t.get('mp-demo').click();
assert.equal(t.get('mp-results').hidden,false);
assert.ok(numeric(t.get('mp-kpi-budget').textContent)>0);
t.get('mp-export').click();
assert.equal(t.downloads.length,1,'Excel export');
t.finish();
console.log('PASS CPC and CPM arithmetic, scenario ordering, demo and Excel export');
